-- Fuelwind: režim Návyky (nikotín, alkohol). Spusti v Supabase SQL Editore.
-- Dáta vidí len používateľ (nie kouč).

create table if not exists public.habits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('nicotine','alcohol')),
  sub text,                               -- cig, vape, snus, chew, cigar | beer, wine, spirit, mixed
  mode text not null default 'quit' check (mode in ('quit','reduce')),
  baseline numeric,                       -- koľko denne pred začiatkom
  daily_limit numeric,                    -- cieľ pri znižovaní
  unit_cost numeric,                      -- cena za 1 kus / nápoj v EUR
  start_date date not null default (now() at time zone 'Europe/Bratislava')::date,
  quit_at timestamptz,                    -- od kedy úplne bez
  active boolean not null default true,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists habits_user_idx on public.habits(user_id, active);

create table if not exists public.habit_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  habit_id bigint not null references public.habits(id) on delete cascade,
  date date not null,
  at timestamptz not null default now(),
  qty numeric not null default 1,         -- 0 = odolaná chuť (výhra), >0 = použitie
  kind text not null,                     -- nicotine | alcohol
  item text,                              -- cig, vape, snus | beer, wine, spirit, mixed
  trigger text,                           -- stress, coffee, social, bored, alcohol, meal, habit, other
  kcal numeric,                           -- kalórie nápoja (alkohol)
  food_log_id bigint,                     -- prepojený zápis v denníku jedla
  note text,
  created_at timestamptz not null default now()
);
create index if not exists habit_logs_user_date_idx on public.habit_logs(user_id, date);
create index if not exists habit_logs_habit_idx on public.habit_logs(habit_id, at);

alter table public.habits enable row level security;
alter table public.habit_logs enable row level security;
drop policy if exists "habits own" on public.habits;
create policy "habits own" on public.habits for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "habit_logs own" on public.habit_logs;
create policy "habit_logs own" on public.habit_logs for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- export údajov (GDPR): pridané habits a habit_logs
create or replace function public.export_my_data()
 returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare u uuid := auth.uid(); r jsonb;
begin
  if u is null then raise exception 'not signed in'; end if;
  select jsonb_build_object(
    'exported_at', now(),
    'profile', (select to_jsonb(p) from profiles p where p.id=u),
    'food_logs', coalesce((select jsonb_agg(to_jsonb(x) order by x.date) from food_logs x where x.user_id=u),'[]'),
    'weight_logs', coalesce((select jsonb_agg(to_jsonb(x) order by x.date) from weight_logs x where x.user_id=u),'[]'),
    'checkins', coalesce((select jsonb_agg(to_jsonb(x) order by x.date) from checkins x where x.user_id=u),'[]'),
    'weekly_checkins', coalesce((select jsonb_agg(to_jsonb(x)) from weekly_checkins x where x.user_id=u),'[]'),
    'workout_plans', coalesce((select jsonb_agg(to_jsonb(x)) from workout_plans x where x.user_id=u),'[]'),
    'workout_logs', coalesce((select jsonb_agg(to_jsonb(x) order by x.date) from workout_logs x where x.user_id=u),'[]'),
    'target_history', coalesce((select jsonb_agg(to_jsonb(x)) from target_history x where x.user_id=u),'[]'),
    'health_daily', coalesce((select jsonb_agg(to_jsonb(x)) from health_daily x where x.user_id=u),'[]'),
    'my_foods', coalesce((select jsonb_agg(to_jsonb(x)) from foods x where x.created_by=u),'[]'),
    'messages', coalesce((select jsonb_agg(to_jsonb(x)) from messages x where x.from_user=u or x.to_user=u),'[]'),
    'glucose_logs', coalesce((select jsonb_agg(to_jsonb(x) order by x.date) from glucose_logs x where x.user_id=u),'[]'),
    'diet_settings', (select to_jsonb(d) from diet_settings d where d.user_id=u),
    'food_checks', coalesce((select jsonb_agg(to_jsonb(x)) from food_checks x where x.user_id=u),'[]'),
    'habits', coalesce((select jsonb_agg(to_jsonb(x)) from habits x where x.user_id=u),'[]'),
    'habit_logs', coalesce((select jsonb_agg(to_jsonb(x) order by x.at) from habit_logs x where x.user_id=u),'[]')
  ) into r;
  return r;
end $function$;
